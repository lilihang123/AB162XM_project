#ifndef _HAL_SW_IRQ_H_
#define  _HAL_SW_IRQ_H_
#include "hal.h"
#include "hal_platform.h"

typedef enum {
    HAL_SW_IRQ_STATUS_NOT_SUPPORTED = -4,
    HAL_SW_IRQ_STATUS_Q_FULL = -3,
    HAL_SW_IRQ_STATUS_INVALID_PARAMETER = -2,
    HAL_SW_IRQ_STATUS_ERROR = -1,
    HAL_SW_IRQ_STATUS_OK = 0,
} hal_sw_irq_status_t;

typedef void (*hal_sw_irq_callback_t) (void *user_data);

typedef struct {
    uint8_t used_flag;
    hal_sw_irq_callback_t call_back;
    void *user_data;
} hal_sw_irq_user_info_t;

hal_sw_irq_status_t hal_sw_irq_trigger(hal_sw_irq_t sw_irq , hal_sw_irq_callback_t user_callback, void *user_data);

#endif